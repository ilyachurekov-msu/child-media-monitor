from pathlib import Path
from sqlalchemy.schema import CreateTable, CreateIndex
from sqlalchemy.dialects import postgresql
from app.models import Base

root = Path(__file__).resolve().parents[1]
(root / 'contracts').mkdir(exist_ok=True)
ddl = []
for table in Base.metadata.sorted_tables:
    ddl.append(str(CreateTable(table).compile(dialect=postgresql.dialect())))
    ddl.extend(str(CreateIndex(i).compile(dialect=postgresql.dialect())) for i in table.indexes)
(root / 'migrations/versions/0001_schema.sql').write_text(';\n'.join(ddl) + ';\n', encoding='utf-8')

